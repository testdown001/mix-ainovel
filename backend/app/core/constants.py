CHAPTER_STYLE_HARD_RULE = (
    "【克制叙事与有限视角硬约束】\n"
    "1) 先写清谁做了什么、发生了什么，再决定是否需要修饰。优先使用精确名词和有结果的动词；删掉后不影响信息的形容词、副词一律删掉。\n"
    "2) 一个句子只保留一个主要意象，一个自然段原则上不超过一次比喻。禁止连续使用“像、仿佛、似乎、宛如、犹如”给同一事物叠加解释。\n"
    "3) 情绪表达优先顺序：选择与行为后果 > 对话与停顿 > 一个简短身体反应。简单情绪允许直陈；同一情绪节拍最多保留一个身体反应，禁止把心跳、冷汗、喉结、指尖、胸腔、目光等写成微动作套装。\n"
    "4) 严格使用当前 POV 的有限视角：只陈述该角色当下可感知、可回忆或有证据可推断的信息。其他角色的真实想法、幕后行动和未来结果不得由旁白直接确认；推断必须写成推断，不得冒充事实。\n"
    "5) 禁止离开当前 POV 切到“与此同时/另一边/无人知道”的后台镜头。角色离场、闭眼或失去意识后，镜头不得留在原地继续叙述。\n"
    "6) 章尾可落在动作、台词、发现、决定或局部问题解决后的具体余波上；保留仍成立的长线期待，不强求新危机或悬崖式断句。最后两段禁止命运、风暴、光影、夜色、种子、火焰、齿轮等象征性点题，也禁止总结本章和预告未来。\n"
    "7) 禁止使用以下空泛词语：深入探讨、细致入微、至关重要、引人注目、精心、层层、宛如、犹如、深刻启示、全面、显著、"
    "meticulously、delve、intricate、tapestry、realm、pivotal。\n"
    "8) 若出现上述词语，必须改写为具体动作、事实或结果描述。\n"
    "9) 章节结尾禁止使用「环境/自然现象+拟人化暗示」来象征角色心态或命运走向。\n"
    "例：「风仿佛在回应……」「有什么正在苏醒/萌芽」「火焰跳了一下像是……」均属违禁。\n"
    "结尾应直接落在角色的动作、一句话、或一个干脆的画面上，不需要环境来「点题」。"
)

# ========== 新增：段落与节奏控制规则 ==========

PARAGRAPH_LENGTH_RULE = (
    "【段落控制硬性要求】\n"
    "1) 单个段落最长不超过150字，超过必须拆分。\n"
    "2) 避免「车轱辘话」——同一观点不要用不同措辞重复两遍以上。\n"
    "3) 心理描写连续不超过3段，超过则必须插入动作或对话打断。\n"
    "4) 景物描写每次不超过2段，必须与剧情推进结合，禁止纯写景超过200字。\n"
    "5) 回忆/闪回每次不超过200字，且必须服务于当前情节。\n"
)

DIALOGUE_RATIO_RULE = (
    "【按章节功能安排对话】\n"
    "1) 对话比例由本章功能、人物处境和场景决定，不设统一下限；独处、行动、余波场景可以少对白或无对白。\n"
    "2) 对话的快慢服从人物意图：交锋可以短促，试探、安慰、告别可以停顿；删去重复解释，不为提速抹掉情绪过程。\n"
    "3) 对话应推进情节、关系或人物认知；日常寒暄若承载关系变化或潜台词可以保留，不为凑比例添加闲聊。\n"
    "4) 动作标签只在说话人切换、情绪转折或信息容易误读时使用；连续2-4句对话可共用一个动作锚点，禁止每句都补表情、目光或手部动作。\n"
    "5) 禁止大段独白——单次内心独白超过150字必须删减。\n"
)

CHAPTER_STRUCTURE_RULE = (
    "【按章节功能安排结构】\n"
    "1) 本章功能和已规划的情绪曲线优先：开篇承接人物处境，尽早建立值得关注的具体事情，不限定冲突出现的字数。\n"
    "2) 全章应留下有意义的剧情、关系或认知变化；压迫章交代不能反击的理由，破局章兑现准备，余波章让得失与代价落下来。\n"
    "3) 关系章写清靠近或疏远，日常章建立可牵挂的生活，揭秘章让新事实改变旧理解；转折、停顿和详略随因果与情绪安排，不按固定字数插入刺激。\n"
    "4) 允许本章的小问题完整解决，让仍成立的长线承诺延续；结尾可以是兑现后的余韵，不强制新危机、反转或硬断章。趣味点只在人物与情境自然时出现。\n"
    "5) 结尾最后一段必须落在角色动作/台词/具体画面上，禁止以议论、抒情、环境描写收尾。\n"
)

SENTENCE_VARIETY_RULE = (
    "【句式变化硬性要求】\n"
    "1) 禁止连续3句以上使用相同句式（主谓宾/主谓/主谓补）。\n"
    "2) 句式变化服从信息和语气，不为达成比例强行倒装、排比或拆句。\n"
    "3) 动作场面可用短句提速，但必须保持动作关系清楚，禁止整段机械地每10字断一句。\n"
    "4) 心理/情感场面可适当放慢，但一次只推进一个判断或矛盾，禁止用长句堆叠感官与修饰。\n"
    "5) 禁止「和」字连续出现超过3次，超过必须拆分或换词。\n"
    "6) 禁止「的」字连续出现超过4次，超过必须简化结构。\n"
)

PROTAGONIST_VOICE_RULE = (
    "【主角人设硬性要求】\n"
    "1) 主角必须有鲜明且统一的行为逻辑——面对同类问题必须做出符合人设的选择。\n"
    "2) 标志性动作或口头禅只在情境自然时出现，不设每章重复次数；连续章节不得机械复用同一身体反应。\n"
    "3) 主角面临的困境/选择必须与其「核心恐惧」或「核心渴望」直接关联。\n"
    "4) 主角必须主动行动推动情节，不能只是被动回应（每章至少1次主动选择/行动）。\n"
    "5) 主角的成长/转变必须有迹可循，不能性格突变——通过具体事件和心理变化展现。\n"
)

SCENE_TRANSITION_RULE = (
    "【场景切换硬性要求】\n"
    "1) 场景切换必须使用「硬切」或「过渡句」，禁止模糊叙事导致时空混乱。\n"
    "2) 切换场景后必须在50字内明确时间/地点/人物，否则读者会困惑。\n"
    "3) 避免同一场景内频繁切换视角——如需切换，用段落分隔并标注。\n"
    "4) 时间跨度超过3个月必须标注明确的时间线或使用时间戳。\n"
    "5) 多线叙事只推进与本章功能相关的线索，按长线计划回访其他线索，不要求每章同时推进所有线。\n"
)

